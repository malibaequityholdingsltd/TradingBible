const I18nContext = createContext(null);

// Non-English locales live in ./i18n.<code>.js chunks, downloaded only when
// selected. English ships in the main bundle. While a locale loads, t()
// falls back to English — never blank.
const inflightLocales = {};
function ensureLocale(code, bump) {
  if (!code || code === 'en' || STRINGS[code] || inflightLocales[code]) return;
  if (!SUPPORTED_LANGS.some((l) => l.code === code)) return;
  inflightLocales[code] = import(`./i18n.${code}.js`)
    .then((m) => { if (m && m.default) { STRINGS[code] = m.default; bump(); } })
    .catch(() => { /* keep English fallback */ })
    .finally(() => { delete inflightLocales[code]; });
}

function plural(n, s) {
  return n === 1 ? '' : s;
}

function interpolate(template, vars = {}) {
  return String(template || '').replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(detectLanguage);
  const [localeTick, setLocaleTick] = useState(0);
  // Admin-curated copy overrides (English only). Loaded async + cached;
  // pages re-render with new copy when it arrives — no reload needed.
  const [copyOverrides, setCopyOverrides] = useState(() => {
    try {
      const raw = window.localStorage.getItem('tb:site-copy-v1');
      if (raw) {
        const parsed = JSON.parse(raw);
        if (parsed && parsed.ts && Date.now() - parsed.ts < 30 * 60 * 1000) return parsed.overrides || {};
      }
    } catch { /* ignore */ }
    return {};
  });

  const setLang = useCallback((next) => {
    if (next === 'auto') {
      try { localStorage.removeItem(LANG_KEY); } catch { /* ignore */ }
      setLangState(detectLanguage());
      return;
    }
    if (!SUPPORTED_LANGS.some((l) => l.code === next)) return;
    try { localStorage.setItem(LANG_KEY, next); } catch { /* ignore */ }
    setLangState(next);
  }, []);

  useEffect(() => {
    try {
      const rtl = lang === 'ar';
      document.documentElement.lang = lang;
      document.documentElement.dir = rtl ? 'rtl' : 'ltr';
      document.documentElement.classList.toggle('tb-rtl', rtl);
    } catch { /* ignore */ }
  }, [lang]);

  useEffect(() => {
    ensureLocale(lang, () => setLocaleTick((n) => n + 1));
  }, [lang]);

  useEffect(() => {
    let live = true;
    (async () => {
      try {
        const res = await fetch(`${API_SERVER_URL}/admin/content-copy`);
        if (res.ok && live) {
          const data = await res.json();
          const next = data?.overrides && typeof data.overrides === 'object' ? data.overrides : {};
          setCopyOverrides(next);
          try { window.localStorage.setItem('tb:site-copy-v1', JSON.stringify({ ts: Date.now(), overrides: next })); } catch { /* ignore */ }
        }
      } catch { /* keep cache/defaults */ }
    })();
    const onChange = () => {
      try { window.localStorage.removeItem('tb:site-copy-v1'); } catch { /* ignore */ }
      setCopyOverrides({});
    };
    window.addEventListener('tb:site-copy:changed', onChange);
    return () => { live = false; window.removeEventListener('tb:site-copy:changed', onChange); };
  }, []);

  const value = useMemo(() => {
    const dict = STRINGS[lang] || STRINGS.en;
    const t = (key, vars, fb) => {
      // Site-copy overrides win for English; other languages keep shipped text.
      if (lang === 'en' && copyOverrides[key] !== undefined) return interpolate(copyOverrides[key], vars);
      return interpolate(dict[key] ?? STRINGS.en[key] ?? fb ?? key, vars);
    };
    return { lang, setLang, t };
  }, [lang, setLang, copyOverrides, localeTick]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

// Pick per-language ad copy overrides (ad.i18n = { hi: { title, headline, cta, snippet } })
// with fallback to the default fields. Lets brand/house ads localize from one DB row.
export function localizeAd(ad, lang) {
  if (!ad) return ad;
  const base = String(lang || 'en').split('-')[0];
  const ov = (ad.i18n && (ad.i18n[base] || ad.i18n.en)) || null;
  if (!ov) return ad;
  return {
    ...ad,
    title: ov.title || ad.title,
    headline: ov.headline || ad.headline,
    cta: ov.cta || ad.cta,
    snippet: ov.snippet || ad.snippet,
  };
}

