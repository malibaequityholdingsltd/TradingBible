// ─── Tiny i18n: auto-detect from device/browser, manual override in localStorage ───
export const SUPPORTED_LANGS = [
  { code: 'en', label: 'English' },
  { code: 'fr', label: 'Français' },
  { code: 'es', label: 'Español' },
  { code: 'pt', label: 'Português' },
  { code: 'de', label: 'Deutsch' },
  { code: 'ar', label: 'العربية' },
  { code: 'zh', label: '中文' },
  { code: 'hi', label: 'हिन्दी' },
];

const LANG_KEY = 'tb_lang';

export function detectLanguage() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && SUPPORTED_LANGS.some((l) => l.code === saved)) return saved;
  } catch { /* ignore */ }
  try {
    const n = (navigator.language || '').toLowerCase().split('-')[0];
    if (SUPPORTED_LANGS.some((l) => l.code === n)) return n;
  } catch { /* ignore */ }
  return 'en';
}

